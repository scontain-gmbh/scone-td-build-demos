#!/usr/bin/env bash
# Post-cleanup flow in sptd mode: before the confidential deployment, each README deletes the native workloads and
# their Secrets (for flask-redis `kubectl delete secret redis-tls flask-tls`), and then applies only the sanitized
# manifest that td-build-sptd.py writes from the Apply files of the sptd scone variant. So every Secret that a
# workload in those Apply files references and that the cleanup deletes must come back through the Apply files,
# baked or not; otherwise the Pod stays in CreateContainerConfigError.
set -euo pipefail
repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
python3 -I - "$repo_root" <<'PY'
import os, re, subprocess, sys
import yaml
root = sys.argv[1]
files = subprocess.run(["git", "-C", root, "ls-files", "*scone*.sptd.template.yaml"], capture_output=True, text=True, check=True).stdout.split()
assert files, "no sptd scone variants found"


def env_of(demo):
    path = os.path.join(root, demo, "Values.yaml")
    values = (yaml.safe_load(open(path)) or {}).get("environment") or {} if os.path.isfile(path) else {}
    return dict(values, SCRIPT_DIR=os.path.join(root, demo))


def render(text, env):
    return re.sub(r"\$\{(\w+)\}", lambda m: str(env.get(m.group(1), m.group(0))), text)


def docs_of(path, env):
    stem = path[:-len(".yaml")]
    for candidate in (stem + ".sptd.template.yaml", stem + ".template.yaml", path):
        if os.path.isfile(candidate):
            return [d for d in yaml.safe_load_all(render(open(candidate).read(), env)) if isinstance(d, dict)]
    return None  # generated at run time (for example the TLS Secrets of README step 4)


def referenced_secrets(doc):
    found = set()
    def walk(value):
        if isinstance(value, dict):
            if isinstance(value.get("secret"), dict) and value["secret"].get("secretName"):
                found.add(value["secret"]["secretName"])
            for key in ("secretKeyRef", "secretRef"):
                if isinstance(value.get(key), dict) and value[key].get("name"):
                    found.add(value[key]["name"])
            for item in value.values():
                walk(item)
        elif isinstance(value, list):
            for item in value:
                walk(item)
    walk(doc.get("spec", {}))
    return found


checked = 0
for rel in files:
    demo = rel.split("/", 1)[0]
    env = env_of(demo)
    readme = open(os.path.join(root, demo, "README.md")).read()
    # Secret files the README generates: `kubectl create ... secret generic <name> ... > <file>`.
    generated = {f: n for n, f in re.findall(r"secret generic (\S+)[^`]*?>\s*(\S+\.yaml)", readme)}
    deleted = {n for line in re.findall(r"kubectl delete secret ([^\n]*)", readme) for n in line.split() if not n.startswith("-") and "$" not in n}
    docs = [d for d in yaml.safe_load_all(render(open(os.path.join(root, rel)).read(), env)) if isinstance(d, dict)]
    for apply in (d["spec"] for d in docs if d.get("kind") == "Apply"):
        names = apply["file"] if isinstance(apply["file"], list) else [apply["file"]]
        provided, referenced = set(), set()
        for name in names:
            path = name if os.path.isabs(name) else os.path.join(root, demo, name)
            contents = docs_of(path, env)
            if contents is None:
                generated_name = generated.get(name)
                assert generated_name, f"{rel}: Apply file {name} is neither in the repository nor generated by the README"
                provided.add(generated_name)
                continue
            for d in contents:
                if d.get("kind") in ("Secret", "SconeSecret"):
                    provided.add(d["metadata"]["name"])
                if d.get("kind") in ("Pod", "Deployment", "StatefulSet", "DaemonSet", "Job", "CronJob"):
                    referenced |= referenced_secrets(d)
        missing = sorted((referenced & deleted) - provided)
        assert not missing, f"{rel}: the cleanup deletes Secret(s) {missing} that a workload mounts, and the Apply files do not bring them back"
        checked += 1
print(f"sptd Apply files bring back every Secret the cleanup deletes ({checked} Apply documents)")
PY

# The flask-redis case of the review: the sptd variant must apply the flask-tls Secret for flask-api (not baked).
python3 -I - "$repo_root" <<'PY'
import json, os, sys
import yaml
root = sys.argv[1]
docs = list(yaml.safe_load_all(open(os.path.join(root, "flask-redis/scone.sptd.template.yaml"))))
files = next(d for d in docs if d["kind"] == "Apply")["spec"]["file"]
assert "k8s/secret-flask-tls.yaml" in files and "k8s/secret-redis-tls.yaml" in files, files
overrides = json.load(open(os.path.join(root, "scripts/sptd/policies/flask-redis.overrides.json")))
baked = {v["name"] for w in overrides["workloads"].values() for c in w["containers"].values() for v in c.get("bakedVolumes", [])}
assert "flask-tls" not in baked, baked
print("flask-redis sptd: flask-tls Secret applied, not baked")
PY
