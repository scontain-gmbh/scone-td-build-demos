#!/usr/bin/env python3
"""Re-onboard every sptd demo against a landed dev node image (docs/sptd-integration.md). NON_RELEASE.

This script never signs and never reads a key. Onboarding and signing are one step
(scone-dev-onboard/onboard.py signs each profile, the registry and each Pod plan with the
dev root key), and that key lives on the devvm only. So the script works in three parts:

  plan      landed-image facts + demos.json -> reonboard-plan.json and reonboard-devvm.sh,
            the exact commands for the devvm. Nothing is run. --dry-run prints the script.
  collect   after the devvm run: the per-step work directories -> an artifact set
            (bundles, node-set/ for provision-dev-registry, Pod plans, output manifests)
            and its manifest.json with the artifact-set hash.
  validate  manifest.json against the pinned schema and every cross-check
            (also: artifact_manifest.py).

  set-values  helper the devvm script uses: upsert environment.KEY in a demo Values.yaml
            (same rule as prepare-example-ci.sh, without its kubectl steps).
"""
import argparse
import datetime
import json
import os
import re
import shlex
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sptdinteg as si  # noqa: E402
import artifact_manifest  # noqa: E402

PLAN_SCHEMA = "sptd-reonboard-plan-v1"
INTEGRATION_FILES = ("sptdinteg.py", "reonboard_all.py", "artifact_manifest.py", "demos.json",
                     "artifact-manifest.schema.json", "landed-image-facts.schema.json")
BAKE_FEATURE = "nonrelease-dev-baked-volumes"


def q(value):
    return shlex.quote(str(value))


# --------------------------------------------------------------------------------------
# plan


def build_plan(facts, facts_path, catalog, demos=None, include_pending=False, node_name=None,
               namespace="default", allow_stand_in=False):
    if facts["standIn"] and not allow_stand_in:
        raise si.Invalid("facts are a stand-in (standIn true): pass --allow-stand-in for a dry-run plan; "
                         "such a plan refuses to run")
    if facts["nodeImage"]["contract"] != "V7":
        raise si.Invalid("Pod plans (configmap and every multi-role demo) need the V7 plan-set node contract")
    steps = si.select_steps(catalog, demos, include_pending)
    if not steps:
        raise si.Invalid("no steps selected")
    phases = [p["name"] for p in catalog["phases"]]
    blocked = [s["id"] for s in si.select_steps(catalog, demos, True) if s["status"] != "ready" and s not in steps]
    # The registry is append-only. A subset run is fine as long as it keeps the catalog
    # order; it produces a different registry (and artifact-set hash) than the full run.
    plan_steps = []
    for index, step in enumerate(steps):
        features = list(step.get("compilerFeatures", []))
        plan_steps.append({
            "index": index + 1,
            "id": step["id"],
            "demo": step["demo"],
            "phase": step["phase"],
            "registryFrom": "base" if index == 0 else steps[index - 1]["id"],
            "dir": step["dir"],
            "render": step["render"],
            "scone": step["scone"],
            "outputManifest": step["outputManifest"],
            "nativeManifests": step["nativeManifests"],
            "supportManifests": step.get("supportManifests", []),
            "requiredEnv": step.get("requiredEnv", []),
            "envContext": step.get("envContext", True),
            "compilerFeatures": features,
            "needs": step.get("needs", []),
            "status": step["status"],
        })
    return {
        "schema": PLAN_SCHEMA,
        "nonRelease": True,
        "signsNothing": True,
        "standIn": facts["standIn"],
        "factsSha256": si.file_sha256(facts_path),
        "catalogSha256": si.file_sha256(si.CATALOG),
        "facts": facts,
        "nodeName": node_name,
        "namespace": namespace,
        "rootPin": "sha256:" + facts["devRegistry"]["rootPin"],
        "baseRegistrySha256": (facts["devRegistry"].get("installedOnImage") or {}).get("registrySha256"),
        "phases": phases,
        "steps": plan_steps,
        "blockedSteps": blocked,
    }


SCRIPT_HEAD = r"""#!/usr/bin/env bash
# Re-onboard and dev-sign the sptd demos on the DEVVM (generated by
# scripts/sptd/integration/reonboard_all.py plan; docs/sptd-integration.md). NON_RELEASE.
#
# Runs ONLY on the devvm, under a typed line. The dev root key never leaves the devvm and is
# never printed: export its path as SPTD_DEV_SIGNING_KEY yourself. This script writes no
# node configuration, pulls nothing (SPTD_A8_OFFLINE=true) and pushes nothing.
#
# Inputs you export before running (paths on the devvm):
#   SPTD_DEV_SIGNING_KEY   dev root signing key (PEM, mode 0600)            -- never printed
#   SPTD_DEMOS             scone-td-build-demos checkout at the facts commit
#   SPTD_ONBOARD_CHECKOUT  sptd-hello-container-dev checkout at the facts commit
#   SPTD_A8_TOOLS          onboard tools JSON (envcas_source at the facts envcas commit)
#   SPTD_SOURCE_LAYOUTS    JSON {source image: OCI layout or oci-archive}
#   SPTD_REONBOARD_WORK    new, empty work directory (needs room for every bundle)
#   SPTD_VALUES_OVERRIDES  optional JSON {step id: {KEY: value}} for the demo Values.yaml
#   SPTD_A8_MEMORY_ASSEMBLY optional, with the memory_empty_dir tool
#   SPTD_BASE_REGISTRY     only when the node image ships a registry: its profile-registry.json
set -euo pipefail
"""


def render_script(plan):
    facts = plan["facts"]
    lines = [SCRIPT_HEAD]
    lines.append(f"# facts sha256 {plan['factsSha256']}  catalog sha256 {plan['catalogSha256']}")
    lines.append(f"# steps: {', '.join(s['id'] for s in plan['steps'])}")
    if plan["blockedSteps"]:
        lines.append(f"# not in this plan (pending): {', '.join(plan['blockedSteps'])}")
    if plan["standIn"]:
        lines += ["", "echo 'STAND-IN facts: this plan is a dry run and must not be used for signing' >&2", "exit 3"]
    lines += [
        "",
        f"ROOT_PIN={q(plan['rootPin'])}",
        f"ENVCAS_COMMIT={q(facts['envcas']['commit'])}",
        f"DEMOS_COMMIT={q(facts['demos']['commit'])}",
        f"ONBOARD_COMMIT={q(facts['onboard']['commit'])}",
        f"NAMESPACE_VALUE={q(plan['namespace'])}",
        f"NODE_NAME={q(plan['nodeName'] or '')}",
        'PLAN_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"',
        '# The integration scripts travel with the plan (PLAN_DIR/integration): the demos commit',
        '# being onboarded need not contain them.',
        'INTEG="$PLAN_DIR/integration"',
        "",
        "# ---- pre-checks (no key material is read or printed) ----",
        ': "${SPTD_DEV_SIGNING_KEY:?export the dev root key path}"',
        ': "${SPTD_DEMOS:?}" "${SPTD_ONBOARD_CHECKOUT:?}" "${SPTD_A8_TOOLS:?}" "${SPTD_SOURCE_LAYOUTS:?}" "${SPTD_REONBOARD_WORK:?}"',
        '[[ "$(stat -c %a "$SPTD_DEV_SIGNING_KEY")" == 600 ]] || { echo "key file must be mode 0600" >&2; exit 2; }',
        '[[ "$(git -C "$SPTD_DEMOS" rev-parse HEAD)" == "$DEMOS_COMMIT" ]] || { echo "demos checkout is not at $DEMOS_COMMIT" >&2; exit 2; }',
        '[[ -z "$(git -C "$SPTD_DEMOS" status --porcelain --untracked-files=no)" ]] || { echo "demos checkout has local changes" >&2; exit 2; }',
        '[[ "$(git -C "$SPTD_ONBOARD_CHECKOUT" rev-parse HEAD)" == "$ONBOARD_COMMIT" ]] || { echo "onboard checkout is not at $ONBOARD_COMMIT" >&2; exit 2; }',
        'ENVCAS_SOURCE="$(python3 -c \'import json,sys; print(json.load(open(sys.argv[1]))["envcas_source"])\' "$SPTD_A8_TOOLS")"',
        '[[ "$(git -C "$ENVCAS_SOURCE" rev-parse HEAD)" == "$ENVCAS_COMMIT" ]] || { echo "envcas_source is not at $ENVCAS_COMMIT" >&2; exit 2; }',
        'mkdir -p "$SPTD_REONBOARD_WORK"',
        '[[ -z "$(ls -A "$SPTD_REONBOARD_WORK")" ]] || { echo "SPTD_REONBOARD_WORK must be empty" >&2; exit 2; }',
        f'[[ "sha256:$(sha256sum "$PLAN_DIR/facts.json" | cut -d" " -f1)" == {q(plan["factsSha256"])} ]] '
        '|| { echo "facts.json next to this script differs from the plan" >&2; exit 2; }',
        f'[[ "sha256:$(sha256sum "$INTEG/demos.json" | cut -d" " -f1)" == {q(plan["catalogSha256"])} ]] '
        '|| { echo "integration/demos.json differs from the plan" >&2; exit 2; }',
        '[[ -x "$SPTD_DEMOS/scripts/sptd/bin/scone-td-build" ]] || { echo "the sptd dispatcher is missing" >&2; exit 2; }',
        "",
        "export TEE_TYPE=sptd SPTD_ROUTE=a8 SPTD_A8_OFFLINE=true",
        'export SPTD_ONBOARD="$SPTD_ONBOARD_CHECKOUT/scone-dev-onboard/onboard.py" SPTD_DEV_ROOT_PIN="$ROOT_PIN"',
        'export SPTD_DEV_SIGNING_KEY SPTD_A8_TOOLS SPTD_SOURCE_LAYOUTS',
        'if [[ -n "$NODE_NAME" ]]; then export SPTD_NODE_NAME="$NODE_NAME"; else unset SPTD_NODE_NAME; fi',
        'export PATH="$SPTD_DEMOS/scripts/sptd/bin:$PATH"',
    ]
    if plan["baseRegistrySha256"]:
        lines += [
            ': "${SPTD_BASE_REGISTRY:?the node image ships a registry; point SPTD_BASE_REGISTRY at it}"',
            f'[[ "sha256:$(sha256sum "$SPTD_BASE_REGISTRY" | cut -d" " -f1)" == {q(plan["baseRegistrySha256"])} ]] '
            '|| { echo "SPTD_BASE_REGISTRY differs from the facts" >&2; exit 2; }',
            'REGISTRY="$SPTD_BASE_REGISTRY"',
        ]
    else:
        lines.append('REGISTRY=""')
    for step in plan["steps"]:
        sid = step["id"]
        out = f'"$SPTD_REONBOARD_WORK/steps/{sid}"'
        lines += ["", f"# ---- step {step['index']}: {sid} ({step['demo']}, phase {step['phase']}, "
                      f"registry from {step['registryFrom']}) ----"]
        lines.append(f'mkdir -p {out}/native {out}/work')
        lines.append(f'cd "$SPTD_DEMOS/{step["dir"]}"')
        lines.append('python3 "$INTEG/reonboard_all.py" set-values Values.yaml TEE_TYPE=sptd '
                     '"SCONE_ENCLAVE=\'false\'" "NAMESPACE=$NAMESPACE_VALUE"')
        lines.append(f'if [[ -n "${{SPTD_VALUES_OVERRIDES:-}}" ]]; then python3 "$INTEG/reonboard_all.py" '
                     f'set-values Values.yaml --from-json "$SPTD_VALUES_OVERRIDES" --step {q(sid)}; fi')
        context = " --context" if step["envContext"] else ""
        lines.append(f'eval "$(tplenv --file environment-variables.md --create-values-file{context} --eval '
                     '${CONFIRM_ALL_ENVIRONMENT_VARIABLES-} --output /dev/null)"')
        for name in step["requiredEnv"]:
            lines.append(f': "${{{name}:?step {sid} needs {name}}}"')
        for argv in step["render"]:
            lines.append(" ".join(q(a) for a in argv))
        env = [f'SPTD_WORK_DIR={out}/work']
        env.append('SPTD_A8_COMPILER_FEATURES=' + q(",".join(step["compilerFeatures"])))
        lines.append('if [[ -n "$REGISTRY" ]]; then export SPTD_A8_REGISTRY="$REGISTRY"; else unset SPTD_A8_REGISTRY; fi')
        lines.append(" ".join(env) + f" scone-td-build apply -f {q(step['scone'])}")
        lines.append(f'cp {q(step["outputManifest"])} {out}/output-manifest.yaml')
        for native in dict.fromkeys(step["nativeManifests"] + step["supportManifests"]):
            lines.append(f'install -D -m 0644 {q(native)} {out}/native/{q(native)}')
        lines.append(f'cp {out}/work/a8/{q(step["demo"])}.summary.json {out}/summary.json')
        lines.append(f'REGISTRY="$(python3 -c \'import json,sys; print(json.load(open(sys.argv[1]))["registry"])\' '
                     f'{out}/summary.json)"')
    lines += [
        "",
        "# ---- collect and validate (public material only; the key is not copied) ----",
        'cd "$SPTD_DEMOS"',
        'python3 "$INTEG/reonboard_all.py" collect --plan "$PLAN_DIR/reonboard-plan.json" '
        '--work "$SPTD_REONBOARD_WORK" --set "$SPTD_REONBOARD_WORK/artifact-set"',
        'python3 "$INTEG/artifact_manifest.py" validate "$SPTD_REONBOARD_WORK/artifact-set/manifest.json" '
        '--deep --facts "$PLAN_DIR/facts.json"',
        'echo "artifact set: $SPTD_REONBOARD_WORK/artifact-set"',
        "",
    ]
    return "\n".join(lines)


def cmd_plan(args):
    facts = si.load_facts(args.facts)
    catalog = si.load_catalog()
    demos = [d for d in (args.demos or "").split(",") if d]
    plan = build_plan(facts, args.facts, catalog, demos, args.include_pending, args.node_name,
                      args.namespace, args.allow_stand_in)
    script = render_script(plan)
    if args.dry_run:
        sys.stdout.write(script)
        print(f"# dry run: {len(plan['steps'])} step(s); nothing written, nothing run", file=sys.stderr)
        return 0
    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "reonboard-plan.json"), "w") as handle:
        json.dump(plan, handle, indent=2, sort_keys=True)
        handle.write("\n")
    shutil.copyfile(args.facts, os.path.join(args.out, "facts.json"))
    integ = os.path.join(args.out, "integration")
    os.makedirs(integ, exist_ok=True)
    for name in INTEGRATION_FILES:
        shutil.copyfile(os.path.join(si.HERE, name), os.path.join(integ, name))
    path = os.path.join(args.out, "reonboard-devvm.sh")
    with open(path, "w") as handle:
        handle.write(script)
    os.chmod(path, 0o755)
    print(f"wrote {args.out}/reonboard-plan.json, facts.json, reonboard-devvm.sh "
          f"({len(plan['steps'])} steps) and integration/; copy the directory to the devvm, outside SPTD_REONBOARD_WORK")
    for step in plan["steps"]:
        print(f"  {step['index']:2d}. {step['id']:24s} phase {step['phase']:14s} registry from {step['registryFrom']}")
    for sid in plan["blockedSteps"]:
        print(f"   -  {sid:24s} pending (not in this plan)")
    return 0


