def _registry_profiles(path):
    registry = si.load_json(path)
    if registry.get("schema") != "sptd-dev-profile-registry-v1" or registry.get("runtime_handler") != "scone-dev":
        raise si.Invalid(f"{path}: not an sptd-dev-profile-registry-v1 for scone-dev")
    return [entry["profile"] for entry in registry["profiles"]], registry


def _copy_tree(source, target, link):
    if os.path.exists(target):
        raise si.Invalid(f"{target} exists; collect needs a fresh --set directory")
    if link:
        shutil.copytree(source, target, copy_function=os.link)
    else:
        shutil.copytree(source, target)


def _digest(value):
    if value is None:
        return None
    return value if value.startswith("sha256:") else "sha256:" + value


def collect(plan, work, set_dir, link=False, now=None):
    """Build the artifact set and its manifest from the devvm work directory."""
    facts = plan["facts"]
    pin = plan["rootPin"]
    if os.path.exists(set_dir) and os.listdir(set_dir):
        raise si.Invalid(f"{set_dir} is not empty")
    os.makedirs(os.path.join(set_dir, "node-set"), exist_ok=True)
    files = {}
    demos, plans, history = [], [], []
    previous = []
    base = plan["baseRegistrySha256"]
    final_registry = None
    for step in plan["steps"]:
        sid = step["id"]
        step_dir = os.path.join(work, "steps", sid)
        summary = si.load_json(os.path.join(step_dir, "summary.json"))
        results = summary["results"]
        refused = [r for r in results if r.get("result") != "PASS"]
        if refused or not results:
            raise si.Invalid(f"step {sid}: {len(refused)} refused role(s); nothing is collected from a refused run")
        registry_path = summary["registry"]
        names, _ = _registry_profiles(registry_path)
        if names[:len(previous)] != previous:
            raise si.Invalid(f"step {sid}: registry does not extend the previous step's registry")
        previous = names
        history.append({"step": sid, "phase": step["phase"], "sha256": si.file_sha256(registry_path),
                        "profileCount": len(names)})
        final_registry = registry_path
        target = os.path.join(set_dir, "steps", sid)
        os.makedirs(os.path.join(target, "native"), exist_ok=True)
        output_rel = f"steps/{sid}/output-manifest.yaml"
        shutil.copyfile(os.path.join(step_dir, "output-manifest.yaml"), os.path.join(set_dir, output_rel))
        files[output_rel] = si.file_sha256(os.path.join(set_dir, output_rel))
        natives, supports = [], []
        for name in dict.fromkeys(step["nativeManifests"] + step["supportManifests"]):
            rel = f"steps/{sid}/native/{name}"
            os.makedirs(os.path.dirname(os.path.join(set_dir, rel)), exist_ok=True)
            shutil.copyfile(os.path.join(step_dir, "native", name), os.path.join(set_dir, rel))
            files[rel] = si.file_sha256(os.path.join(set_dir, rel))
            if name in step["nativeManifests"]:
                natives.append(rel)
            if name in step["supportManifests"]:
                supports.append(rel)
        roles, plan_names = [], {}
        for result in results:
            bundle_src = result["bundle"]
            request = si.load_json(os.path.join(os.path.dirname(bundle_src), "request.json"))
            report = si.load_json(os.path.join(bundle_src, "bundle.json"))
            if report.get("rootPin") != pin or report.get("runtimeReady") is not False:
                raise si.Invalid(f"step {sid}: bundle {bundle_src} is not a runtimeReady:false bundle for {pin}")
            workload = result["workload"]
            rel_bundle = f"bundles/{sid}/{workload.split('/', 1)[1]}/{result['container']}"
            _copy_tree(bundle_src, os.path.join(set_dir, rel_bundle), link)
            for name in ("checksums.json", "bundle.json"):
                files[f"{rel_bundle}/{name}"] = si.file_sha256(os.path.join(set_dir, rel_bundle, name))
            checksums = si.load_json(os.path.join(set_dir, rel_bundle, "checksums.json"))
            if report.get("schema") == "scone-dev-onboard-bundle-v2":
                launcher = _digest((report.get("bootstrapToolDigests") or {}).get("launcher_sha256"))
            else:
                launcher = checksums.get("envcas-rs")
            image = result["image"]
            entry = {
                "workload": workload, "container": result["container"], "profile": request["profile_id"],
                "sourceImage": result["source"], "imageReference": image,
                "imageManifestDigest": image.rsplit("@", 1)[1],
                "podPlan": None,
                "bundle": {
                    "dir": rel_bundle, "schema": report["schema"],
                    "checksumsSha256": files[f"{rel_bundle}/checksums.json"],
                    "bundleJsonSha256": files[f"{rel_bundle}/bundle.json"],
                    "profileDigest": report["profileDigest"], "contractDigest": report["contractDigest"],
                    "artifactDigest": report["artifactDigest"], "imageConfigDigest": report["imageConfigDigest"],
                },
            }
            if launcher:
                entry["bundle"]["launcherSha256"] = launcher
            if result.get("podPlan"):
                plan_json = result["podPlan"]
                if plan_json not in plan_names:
                    plan_names[plan_json] = _collect_plan(step_dir, sid, plan_json, set_dir, files, plans)
                entry["podPlan"] = plan_names[plan_json]
            roles.append(entry)
        record = {"id": sid, "phase": step["phase"], "outputManifest": output_rel, "nativeManifests": natives,
                  "roles": roles}
        if supports:
            record["supportManifests"] = supports
        if demos and demos[-1]["demo"] == step["demo"]:
            demos[-1]["steps"].append(record)
        else:
            demos.append({"demo": step["demo"], "steps": [record]})
    for suffix in ("", ".sig", ".root.pem"):
        rel = f"node-set/profile-registry.json{suffix}"
        shutil.copyfile(final_registry + suffix, os.path.join(set_dir, rel))
        files[rel] = si.file_sha256(os.path.join(set_dir, rel))
    manifest = {
        "schema": "sptd-demo-artifact-manifest-v1",
        "nonRelease": True,
        "createdAt": (now or datetime.datetime.now(datetime.timezone.utc)).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "catalogSha256": plan["catalogSha256"],
        "nodeName": plan["nodeName"],
        "namespace": plan["namespace"],
        "facts": {
            "sha256": plan["factsSha256"], "standIn": facts["standIn"],
            "nodeImageDigest": facts["nodeImage"]["digest"], "nodeContract": facts["nodeImage"]["contract"],
            "managerId": facts["managerId"], "goRootArtifactDigest": facts["goRoot"]["artifactDigest"],
            "envcasCommit": facts["envcas"]["commit"], "launcherRoute": facts["launcher"]["route"],
            "launcherSha256": facts["launcher"]["sha256"], "rootPin": facts["devRegistry"]["rootPin"],
        },
        "sources": {"demosCommit": facts["demos"]["commit"], "onboardCommit": facts["onboard"]["commit"]},
        "registry": {
            "dir": "node-set",
            "sha256": files["node-set/profile-registry.json"],
            "sigSha256": files["node-set/profile-registry.json.sig"],
            "rootPemSha256": files["node-set/profile-registry.json.root.pem"],
            "profiles": previous,
            "history": history,
            "installMode": "append" if base else "fresh",
        },
        "podPlans": plans,
        "demos": demos,
        "files": dict(sorted(files.items())),
    }
    manifest["artifactSetSha256"] = si.artifact_set_sha256(manifest)
    path = os.path.join(set_dir, "manifest.json")
    with open(path, "w") as handle:
        json.dump(manifest, handle, indent=2, sort_keys=True)
        handle.write("\n")
    return manifest


def _collect_plan(step_dir, sid, plan_json, set_dir, files, plans):
    """Copy one signed Pod plan into node-set/pod-plans/ under a name provision-dev-registry accepts."""
    digest = si.file_sha256(plan_json)
    collected = os.path.join(step_dir, "work", "a8", "pod-plans")
    stem = None
    for name in sorted(os.listdir(collected)) if os.path.isdir(collected) else []:
        if name.endswith(".pod-plan.json") and si.file_sha256(os.path.join(collected, name)) == digest:
            stem = name[: -len(".pod-plan.json")]
    if stem is None or "_" not in stem:
        raise si.Invalid(f"step {sid}: Pod plan {plan_json} is not in the run's pod-plans collection")
    namespace, pod_name = stem.split("_", 1)
    name = si.plan_file_name(namespace, pod_name)
    if any(p["name"] == name for p in plans):
        raise si.Invalid(f"two Pod plans for {namespace}/{pod_name}")
    os.makedirs(os.path.join(set_dir, "node-set", "pod-plans"), exist_ok=True)
    digests = {}
    for suffix in ("", ".sig", ".root.pem"):
        rel = f"node-set/pod-plans/{name}.json{suffix}"
        shutil.copyfile(plan_json + suffix, os.path.join(set_dir, rel))
        files[rel] = digests[suffix] = si.file_sha256(os.path.join(set_dir, rel))
    plans.append({"name": name, "step": sid, "namespace": namespace, "podName": pod_name, "sha256": digests[""],
                  "sigSha256": digests[".sig"], "rootPemSha256": digests[".root.pem"]})
    return name


def cmd_collect(args):
    plan = si.load_json(args.plan)
    if plan.get("schema") != PLAN_SCHEMA:
        raise si.Invalid(f"{args.plan}: not a {PLAN_SCHEMA}")
    manifest = collect(plan, args.work, args.set, link=args.link)
    print(f"artifact set {args.set}: {manifest['artifactSetSha256']}")
    return 0


