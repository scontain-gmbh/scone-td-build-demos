def upsert_values(text, key, value):
    """Port of prepare-example-ci.sh upsert_scalar: set environment.KEY in a Values.yaml text."""
    out, found, inside = [], False, False
    for line in text.splitlines():
        if re.match(r"^environment:\s*$", line):
            inside = True
            out.append(line)
            continue
        if inside and line.startswith(f"  {key}:"):
            out.append(f"  {key}: {value}")
            found = True
            continue
        if inside and not line.startswith("  "):
            if not found:
                out.append(f"  {key}: {value}")
                found = True
            inside = False
        out.append(line)
    if inside and not found:
        out.append(f"  {key}: {value}")
        found = True
    if not found:
        raise si.Invalid("Values.yaml has no environment: block")
    return "\n".join(out) + "\n"


def cmd_set_values(args):
    pairs = []
    for item in args.pairs:
        key, sep, value = item.partition("=")
        if not sep or not re.fullmatch(r"[A-Z_][A-Z0-9_]*", key):
            raise si.Invalid(f"expected KEY=value, got {item!r}")
        pairs.append((key, value))
    if args.from_json:
        if not args.step:
            raise si.Invalid("--from-json needs --step")
        overrides = si.load_json(args.from_json).get(args.step, {})
        pairs += sorted(overrides.items())
    with open(args.values) as handle:
        text = handle.read()
    for key, value in pairs:
        text = upsert_values(text, key, value)
    with open(args.values, "w") as handle:
        handle.write(text)
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(prog="reonboard_all.py", description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("plan", help="write the devvm plan and script (signs nothing, runs nothing)")
    p.add_argument("--facts", required=True)
    p.add_argument("--out", help="directory for reonboard-plan.json, facts.json, reonboard-devvm.sh")
    p.add_argument("--demos", help="comma-separated subset, kept in catalog order")
    p.add_argument("--include-pending", action="store_true", help="also plan steps whose status is pending")
    p.add_argument("--node-name", help="nodeName written into every confidential Pod and Pod plan")
    p.add_argument("--namespace", default="default", help="NAMESPACE for every demo (Pod plans bind it)")
    p.add_argument("--allow-stand-in", action="store_true", help="accept stand-in facts (the script then refuses to run)")
    p.add_argument("--dry-run", action="store_true", help="print the devvm script; write nothing")
    c = sub.add_parser("collect", help="build the artifact set and manifest after the devvm run")
    c.add_argument("--plan", required=True)
    c.add_argument("--work", required=True)
    c.add_argument("--set", required=True)
    c.add_argument("--link", action="store_true", help="hard-link bundle files instead of copying")
    v = sub.add_parser("validate", help="same as artifact_manifest.py validate")
    artifact_manifest.add_validate_arguments(v)
    s = sub.add_parser("set-values", help="upsert environment.KEY=value in a Values.yaml")
    s.add_argument("values")
    s.add_argument("pairs", nargs="*")
    s.add_argument("--from-json")
    s.add_argument("--step")
    args = parser.parse_args(argv)
    if args.command == "plan" and not args.dry_run and not args.out:
        parser.error("plan needs --out or --dry-run")
    try:
        return {"plan": cmd_plan, "collect": cmd_collect, "validate": artifact_manifest.cmd_validate,
                "set-values": cmd_set_values}[args.command](args)
    except (si.Invalid, OSError, KeyError, ValueError) as error:
        print(f"reonboard_all.py {args.command}: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
